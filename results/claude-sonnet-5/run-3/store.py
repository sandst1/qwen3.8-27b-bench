"""SQLite persistence.

The `items` table is an archive of everything we have ever seen, mostly so
that we can answer "did this ever come through?" when someone asks.

The `deliveries` table is what actually prevents the digest from repeating
itself: it remembers, per channel, which items have already been sent so a
later cron tick (run every 15 minutes) doesn't re-notify people about
articles that haven't changed since the last poll.

Item identity for deduping is the `link`, not `raw_id`. See feeds.py: the
"blogroll" format has no id at all, and the "generic" format's guid gets
regenerated by the provider whenever an item is edited (typos, retitles).
`link` is the one field every format produces that stays stable for the
life of an article, so it's what we key deliveries on.
"""

import sqlite3

SCHEMA = """
CREATE TABLE IF NOT EXISTS items (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    source      TEXT NOT NULL,
    raw_id      TEXT,
    title       TEXT NOT NULL,
    link        TEXT NOT NULL,
    summary     TEXT,
    published   TEXT,
    first_seen  TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_items_source ON items(source);

CREATE TABLE IF NOT EXISTS deliveries (
    channel     TEXT NOT NULL,
    link        TEXT NOT NULL,
    sent_at     TEXT NOT NULL DEFAULT (datetime('now')),
    PRIMARY KEY (channel, link)
);
"""


def connect(path):
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    conn.executescript(SCHEMA)
    conn.commit()
    return conn


def record_items(conn, source, items):
    conn.executemany(
        "INSERT INTO items (source, raw_id, title, link, summary, published)"
        " VALUES (?, ?, ?, ?, ?, ?)",
        [
            (source, i["raw_id"], i["title"], i["link"], i.get("summary"), i.get("published"))
            for i in items
        ],
    )
    conn.commit()


def count_items(conn):
    return conn.execute("SELECT COUNT(*) AS n FROM items").fetchone()["n"]


def undelivered(conn, channel, items):
    """Return the subset of `items` not yet recorded as sent to `channel`."""
    if not items:
        return []
    links = list({i["link"] for i in items})
    placeholders = ",".join("?" * len(links))
    rows = conn.execute(
        f"SELECT link FROM deliveries WHERE channel = ? AND link IN ({placeholders})",
        [channel, *links],
    )
    already_sent = {r["link"] for r in rows}
    return [i for i in items if i["link"] not in already_sent]


def mark_delivered(conn, channel, items):
    conn.executemany(
        "INSERT OR IGNORE INTO deliveries (channel, link) VALUES (?, ?)",
        [(channel, i["link"]) for i in items],
    )
    conn.commit()
