"""Regression tests for the "same item every 15 minutes" bug.

Run with: python3 -m unittest -v

The root cause was that store.py archived every item it saw but nothing
ever read the archive back, so digest.run_once re-sent whatever was
currently in a feed's window on every cron tick. The fix is a per-format
`dedupe_key` (see feeds.py) checked against the archive before anything
goes into a digest (see store.filter_unseen / digest.run_once).

fixtures/snapshot-a -> fixtures/snapshot-b encode the three ways "same
item, different identity" happens in practice, one per feed format:

  * newsroom: same entry_id, link changes (utm_campaign bump).
  * blogroll: same permalink, title/excerpt edited, no raw_id at all.
  * wire (generic): same link, guid regenerated because of the edit.

A dedupe strategy that only trusts raw_id, or only trusts the link, passes
some of these and silently fails the others -- that's what
test_snapshot_b_only_sends_the_genuinely_new_item is guarding against.
"""

import contextlib
import io
import tempfile
import unittest
from pathlib import Path

import digest
import store

FIXTURES = Path(__file__).parent / "fixtures"


def cfg_for(snapshot):
    base = FIXTURES / snapshot
    return {
        "feeds": [
            {"name": "newsroom", "format": "newsroom", "url": str(base / "newsroom.json")},
            {"name": "blogroll", "format": "blogroll", "url": str(base / "blogroll.json")},
            {"name": "wire", "format": "generic", "url": str(base / "wire.json")},
        ],
        "channels": [
            {"name": "everything", "type": "stdout", "title": "Firehose", "keywords": []},
        ],
    }


def run(cfg, db, dry_run=False):
    """Run once, capturing what the stdout channel actually printed."""
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        sent = digest.run_once(cfg, db, dry_run=dry_run)
    return sent, buf.getvalue()


class DedupeTests(unittest.TestCase):
    def setUp(self):
        self.tmpdir = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmpdir.cleanup)
        self.db = store.connect(str(Path(self.tmpdir.name) / "digest.sqlite3"))
        self.addCleanup(self.db.close)

    def test_first_poll_sends_all_six_items(self):
        sent, out = run(cfg_for("snapshot-a"), self.db)
        self.assertEqual(sent, 6)
        self.assertEqual(out.count("* "), 6)

    def test_next_cron_tick_with_unchanged_feed_sends_nothing(self):
        run(cfg_for("snapshot-a"), self.db)
        sent, out = run(cfg_for("snapshot-a"), self.db)
        self.assertEqual(sent, 0)
        self.assertEqual(out, "")  # nothing matched, so no channel section at all

    def test_dry_run_preview_does_not_consume_items(self):
        run(cfg_for("snapshot-a"), self.db, dry_run=True)
        run(cfg_for("snapshot-a"), self.db, dry_run=True)
        sent, _ = run(cfg_for("snapshot-a"), self.db)
        self.assertEqual(sent, 6, "a --dry-run preview must not mark items as seen")

    def test_snapshot_b_only_sends_the_genuinely_new_item(self):
        run(cfg_for("snapshot-a"), self.db)
        sent, out = run(cfg_for("snapshot-b"), self.db)

        self.assertEqual(sent, 1)
        self.assertEqual(out.count("* "), 1)
        self.assertIn("Union responds to port fee inquiry", out)

        # The three traps -- same underlying item resurfacing under a
        # changed identity must NOT look "new":
        self.assertNotIn("Regulator opens inquiry into port fees", out)  # newsroom: url's utm_campaign changed
        self.assertNotIn("Notes on port fee arithmetic", out)  # blogroll: no raw_id; permalink unchanged
        self.assertNotIn("Port fee inquiry opened", out)  # wire: guid regenerated by the edit


if __name__ == "__main__":
    unittest.main()
