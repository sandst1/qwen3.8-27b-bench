"""SQLite persistence.

Two tables live here:

  items
    An append-only archive of every item ever fetched, useful for auditing
    ("did this ever come through?").  Nothing in the send path reads it.

  sent_fingerprints
    One row per item *per channel* that has actually been delivered.
    digest.py consults this before sending so that the same item is never
    delivered to the same channel twice, even if it keeps appearing in the
    feed on subsequent cron runs.

── Why fingerprints instead of raw_id? ─────────────────────────────────────
The three feed formats give us wildly different identifiers:

  • newsroom  – stable entry_id, but the URL gains/loses UTM params across
                fetches, so we can't use the URL directly.
  • blogroll  – no identifier at all (raw_id is always None).
  • generic   – guid is regenerated by the provider on every edit, so it
                cannot be trusted as a stable key.

The one thing that *is* stable for all three is the canonical URL (permalink /
link) once we strip query-string noise.  We combine (source, stripped_link)
into a short SHA-256 fingerprint.  That gives us:

  • A fixed-width, index-friendly column.
  • Immunity to UTM / tracking parameters being added or removed.
  • No dependency on the provider's own ID scheme.

See `fingerprint()` below for the exact stripping logic.
────────────────────────────────────────────────────────────────────────────
"""

import hashlib
import sqlite3
from urllib.parse import urlparse, urlunparse, parse_qs, urlencode

# Query-string keys that feeds append inconsistently.  Strip them before
# hashing so that the same article doesn't look like a new one just because
# a UTM campaign tag was added or rotated.
_STRIP_PARAMS = frozenset(
    {
        "utm_source", "utm_medium", "utm_campaign", "utm_term", "utm_content",
        "ref", "source", "fbclid", "gclid",
    }
)

SCHEMA = """
CREATE TABLE IF NOT EXISTS items (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    source      TEXT NOT NULL,
    raw_id      TEXT,
    title       TEXT NOT NULL,
    link        TEXT NOT NULL,
    summary     TEXT,
    published   TEXT,
    first_seen  TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_items_source ON items(source);

-- One row per (fingerprint, channel).  Inserting here is the "mark as sent"
-- operation; querying here is the deduplication check.
CREATE TABLE IF NOT EXISTS sent_fingerprints (
    fingerprint TEXT NOT NULL,
    channel     TEXT NOT NULL,
    sent_at     TEXT NOT NULL DEFAULT (datetime('now')),
    PRIMARY KEY (fingerprint, channel)
);
"""


def fingerprint(item):
    """Return a stable 16-hex-char key for *item* based on (source, link).

    The link is normalised by dropping known tracking query parameters so that
    UTM variants of the same URL hash to the same value.
    """
    parsed = urlparse(item["link"])
    qs = {k: v for k, v in parse_qs(parsed.query).items() if k not in _STRIP_PARAMS}
    # Rebuild with only the non-noise params; sort for determinism.
    clean_qs = urlencode(sorted(qs.items()), doseq=True)
    clean_url = urlunparse(parsed._replace(query=clean_qs))
    key = f"{item['source']}\x00{clean_url}"
    return hashlib.sha256(key.encode()).hexdigest()[:16]


def connect(path):
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    conn.executescript(SCHEMA)
    conn.commit()
    return conn


def record_items(conn, source, items):
    """Archive fetched items.  Duplicate rows are ignored (same source+link)."""
    conn.executemany(
        "INSERT INTO items (source, raw_id, title, link, summary, published)"
        " VALUES (?, ?, ?, ?, ?, ?)",
        [
            (source, i["raw_id"], i["title"], i["link"], i.get("summary"), i.get("published"))
            for i in items
        ],
    )
    conn.commit()


def already_sent(conn, fp, channel):
    """Return True if *fp* has already been delivered to *channel*."""
    row = conn.execute(
        "SELECT 1 FROM sent_fingerprints WHERE fingerprint = ? AND channel = ?",
        (fp, channel),
    ).fetchone()
    return row is not None


def mark_sent(conn, fp, channel):
    """Record that *fp* was successfully delivered to *channel*."""
    conn.execute(
        "INSERT OR IGNORE INTO sent_fingerprints (fingerprint, channel) VALUES (?, ?)",
        (fp, channel),
    )
    conn.commit()


def count_items(conn):
    return conn.execute("SELECT COUNT(*) AS n FROM items").fetchone()["n"]
